#!/usr/bin/env python3
"""Import the Dreamina fortress art and derive the gameplay data from it (v0.7.1: no warping).

    python3 tools/assets/import_fortress.py <original.png> <cutout.png>

* The source is a 9:16 image (1440 x 2560): at the AI detail tier (res 4 texels per world px) its
  height is exactly the map height (640 world px). It is placed at x = 0 with its proportions
  untouched — the game's geometry follows the art, not the other way round.
* Alpha: everything left of the wall's outer face is opaque (Remove BG punches holes into dark
  rooftops); right of it the cutout's alpha keeps towers, banners and chains; the empty
  battlefield ground of the image becomes transparent.
* Walkable profile: per world row, the outer face of the wall body (cutout opened with a 24-texel
  disc first, so hanging banners and chains don't count), median-smoothed.
* Lights, in world px: torch flames (orange-red: g/r < 0.65, almost no blue — the yellowed bones
  sit at g/r >= 0.73 and must not glow), the portcullis (largest necro-green blob near the gate) and
  every lit window of the citadel (small green blobs).
* Writes assets/sprites/buildings/ai/fortress.png (+ an `images` entry in manifest_ai.json) and the
  generated src/data/fortress_fit.ts.
"""
import json, math, sys, os
import numpy as np
from PIL import Image
from scipy import ndimage

RES = 4
WH = 640
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def blobs(mask, dilate, min_px):
    lab, n = ndimage.label(ndimage.binary_dilation(mask, iterations=dilate) if dilate else mask)
    out = []
    for i, sl in enumerate(ndimage.find_objects(lab), 1):
        m = (lab[sl] == i) & mask[sl]
        c = int(m.sum())
        if c < min_px: continue
        cy, cx = ndimage.center_of_mass(m)
        out.append({'px': c, 'x': (sl[1].start + cx) / RES, 'y': (sl[0].start + cy) / RES,
                    'w': (sl[1].stop - sl[1].start) / RES, 'h': (sl[0].stop - sl[0].start) / RES})
    return out


def main(orig_path, cut_path):
    orig = np.array(Image.open(orig_path).convert('RGB'))
    alpha = np.array(Image.open(cut_path).convert('RGBA'))[:, :, 3]
    H, W = alpha.shape
    assert H == WH * RES, f'expected {WH * RES} texel rows, got {H}'
    solid = alpha > 128
    lab, n = ndimage.label(solid)
    if n > 1:  # drop specks (corner badge, stray pixels)
        sizes = ndimage.sum(solid, lab, range(1, n + 1))
        keep = np.zeros(n + 1, bool); keep[1:] = sizes >= 400
        solid = keep[lab]
    # wall body: open away thin banners / chains, then the rightmost texel per row
    yy, xx = np.mgrid[-12:13, -12:13]
    body = ndimage.binary_opening(solid, structure=(xx * xx + yy * yy) <= 144)
    right = np.array([np.max(np.where(r)[0]) if r.any() else -1 for r in body], float)
    ok = right >= 0
    right[~ok] = np.interp(np.where(~ok)[0], np.where(ok)[0], right[ok])
    face = ndimage.median_filter(right, size=61, mode='nearest')     # ±7 world px
    # alpha: opaque citadel up to 40 texels inside the face, cutout alpha beyond
    a = solid.copy()
    for y in range(H):
        a[y, :max(0, int(face[y]) - 40)] = True
    OW = int(np.max(np.where(a.any(axis=0))[0])) + 1
    OW += (-OW) % RES
    img = Image.fromarray(np.dstack([orig[:, :OW], (a[:, :OW] * 255).astype(np.uint8)]), 'RGBA')
    out_rel = 'sprites/buildings/ai/fortress.png'
    out = os.path.join(ROOT, 'assets', out_rel)
    os.makedirs(os.path.dirname(out), exist_ok=True)
    img.save(out, optimize=True)

    prof = [int(round(max(face[wy * RES:(wy + 1) * RES]) / RES)) for wy in range(WH)]

    o = orig.astype(int)
    r_, g_, b_ = o[..., 0], o[..., 1], o[..., 2]
    rf = np.maximum(r_, 1)
    torch = (r_ > 180) & (g_ / rf < 0.65) & (b_ / rf < 0.15) & a
    green = (g_ > 90) & (g_ > r_ + 35) & (g_ > b_ + 20) & a
    lights = []
    for t in blobs(torch, 2, 60):
        lights.append({'x': round(t['x']), 'y': round(t['y']) - 2, 'r': 34, 'color': '#ff9a2e', 'flicker': True})
    gb = blobs(green, 3, 10)
    # the portcullis: the bars come out as several blobs; merge everything within 30 px of the biggest
    gb.sort(key=lambda t: -t['px'])
    gate = gb[0]
    bars = [t for t in gb if math.hypot(t['x'] - gate['x'], t['y'] - gate['y']) < 30]
    tot = sum(t['px'] for t in bars)
    port = {'x': round(sum(t['x'] * t['px'] for t in bars) / tot), 'y': round(sum(t['y'] * t['px'] for t in bars) / tot)}
    lights.append({'x': port['x'], 'y': port['y'], 'r': 64, 'color': '#5dff7a'})
    for t in gb:
        if t in bars: continue
        lights.append({'x': round(t['x']), 'y': round(t['y']), 'r': 14 if t['px'] < 60 else 20, 'color': '#5dff7a'})

    ts = os.path.join(ROOT, 'src', 'data', 'fortress_fit.ts')
    with open(ts, 'w') as f:
        f.write('// GENERATED by tools/assets/import_fortress.py — do not edit by hand.\n')
        f.write('// Measured from the Dreamina fortress art (art_source/dreamina/fortress_v1), placed unscaled at x = 0.\n')
        f.write(f'export const FORT_FIT = {{ width: {OW // RES}, res: {RES} }};\n')
        f.write('/** Outer face of the fortress per world row (world px): everything left of it is solid. */\n')
        f.write(f'export const FORT_PROFILE: number[] = {json.dumps(prof, separators=(",", ":"))};\n')
        f.write(f'/** Centre of the glowing portcullis (world px). */\nexport const FORT_PORTCULLIS = {json.dumps(port)};\n')
        f.write('export const FORT_FIT_LIGHTS: { x: number; y: number; r: number; color: string; flicker?: boolean }[] = ' + json.dumps(lights) + ';\n')

    man_p = os.path.join(ROOT, 'assets', 'data', 'manifest_ai.json')
    man = json.load(open(man_p))
    man.setdefault('images', {})['fortress'] = {'file': out_rel, 'res': RES, 'w': OW, 'h': H}
    json.dump(man, open(man_p, 'w'), indent=1)
    nt = sum(1 for l in lights if l['color'] == '#ff9a2e')
    print(f'wrote {out_rel} {OW}x{H} texels ({OW // RES}x{WH} world px); {nt} torches, {len(lights) - nt - 1} windows; '
          f'portcullis {port}; face: top {prof[0]}, gate row {prof[port["y"]]}, bottom {prof[-1]}, min {min(prof)}, max {max(prof)}')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
