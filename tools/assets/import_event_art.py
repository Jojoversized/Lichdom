#!/usr/bin/env python3
"""Imports Dreamina story-event scene art (16:9) into the game.

    python3 tools/assets/import_event_art.py <event id> <original image> [--keep-badge]

- keeps the untouched original in art_source/dreamina/events/<id>/original.<ext> with meta.json
  (prompt from tools/assets/event_scenes.json, model, credits);
- crops away the generator's 'AI' corner badge (top-left) while keeping 16:9 (an 89% centred-right
  window starting below the badge);
- downsamples to a 384x216 pixel canvas (box filter: the AI 'pixels' are ~5-7 px, so this lands near
  their native grid), then palette-quantizes (48 colours, no dither) like the in-game pixel art;
- writes assets/ui/events/<id>.png (shown at 2x, image-rendering: pixelated) and regenerates
  src/data/event_art.ts (the list of events that have art).
"""
import argparse, json, os, shutil, sys
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
W, H = 384, 216


def process(src: str, keep_badge=False) -> Image.Image:
    im = Image.open(src).convert('RGB')
    w, h = im.size
    if not keep_badge:
        # badge sits at about x 2-7%, y 3-10%: start the window below it, keep 16:9 (89% of each side)
        s = 0.89
        cw, ch = w * s, h * s
        x0 = (w - cw) / 2; y0 = h - ch
        im = im.crop((round(x0), round(y0), round(x0 + cw), round(y0 + ch)))
    im = im.resize((W, H), Image.BOX)
    im = im.quantize(colors=48, method=Image.MEDIANCUT, dither=Image.NONE).convert('RGB')
    return im


def write_list():
    d = os.path.join(ROOT, 'assets', 'ui', 'events')
    ids = sorted(f[:-4] for f in os.listdir(d) if f.endswith('.png')) if os.path.isdir(d) else []
    with open(os.path.join(ROOT, 'src', 'data', 'event_art.ts'), 'w') as f:
        f.write('// Generated by tools/assets/import_event_art.py — story events that have scene art (assets/ui/events/<id>.png).\n')
        f.write('export const EVENT_ART: string[] = [' + ', '.join(f"'{i}'" for i in ids) + '];\n')
    return ids


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('id'); ap.add_argument('src', nargs='?')
    ap.add_argument('--keep-badge', action='store_true')
    ap.add_argument('--list-only', action='store_true')
    a = ap.parse_args()
    if a.list_only:
        print(write_list()); return
    scenes = json.load(open(os.path.join(ROOT, 'tools', 'assets', 'event_scenes.json')))
    if a.id not in scenes: sys.exit(f'unknown event id {a.id} (not in event_scenes.json)')
    out = os.path.join(ROOT, 'art_source', 'dreamina', 'events', a.id)
    os.makedirs(out, exist_ok=True)
    ext = os.path.splitext(a.src)[1].lower() or '.png'
    shutil.copy(a.src, os.path.join(out, 'original' + ext))
    json.dump({
        'asset': f'event_{a.id}', 'used_as': f'assets/ui/events/{a.id}.png (story event scene art)',
        'tool': 'Dreamina (dreamina.capcut.com) - AI Image', 'model': 'Seedream 4.6',
        'settings': {'ratio': '16:9', 'resolution': '2K', 'images_per_run': 1},
        'reference': 'original Lichdom style reference image (Undead lich army pixel art session)',
        'postprocess': 'tools/assets/import_event_art.py: badge crop (89% window), box downsample to 384x216, 48-colour quantize',
        'credits_spent': {'generation_1_image': 2}, 'date': '2026-11-08',
        'prompt': scenes['_prefix'] + scenes[a.id] + scenes['_suffix'],
    }, open(os.path.join(out, 'meta.json'), 'w'), indent=1)
    dst = os.path.join(ROOT, 'assets', 'ui', 'events'); os.makedirs(dst, exist_ok=True)
    process(a.src, a.keep_badge).save(os.path.join(dst, a.id + '.png'), optimize=True)
    write_list()
    print('ok', a.id)


if __name__ == '__main__':
    main()
